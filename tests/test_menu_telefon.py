"""Menu telefon: bar atas (Utama, Inbox, Menu) + laci menegak berkategori; desktop kekal sidebar."""
import subprocess, sys, time, os
from playwright.sync_api import sync_playwright
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'site')
srv = subprocess.Popen([sys.executable, '-m', 'http.server', '8821'], cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
fails = []; SH = '/tmp/claude-0/-home-claude/7fc64f2f-22b2-5147-8052-ef8c7da90f0a/scratchpad/'
def check(n, ok, d=''):
    print(('PASS ' if ok else 'FAIL ') + n, d if not ok else '')
    if not ok: fails.append(n)
def boot(ctx):
    pg = ctx.new_page(); errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8821/index.html'); pg.wait_for_function("typeof newWorld==='function'", timeout=20000)
    pg.wait_for_function("!document.getElementById('splash')||getComputedStyle(document.getElementById('splash')).pointerEvents==='none'"); time.sleep(.5)
    pg.evaluate("()=>{UI.screen='game';newWorld();UI.selClub=S.lg[3][0];renderStart();document.getElementById('mgr').value='Uji';ACT.startgame()}")
    return pg, errs
with sync_playwright() as p:
    b = p.chromium.launch()
    inv = "localStorage.setItem('pk3-invite', JSON.stringify({code:'AUTO',adm:0,at:'2026-10-28'}));localStorage.setItem('pk3-hidehelp','1')"
    m = b.new_context(viewport={'width': 390, 'height': 800}, has_touch=True, is_mobile=True); m.add_init_script(inv)
    m.route('**/*', lambda r: r.abort() if 'fonts.g' in r.request.url else r.continue_())
    pg, errs = boot(m)
    vis = lambda sel: pg.evaluate("(s)=>{const e=document.querySelector(s);return !!e&&getComputedStyle(e).display!=='none'&&e.getBoundingClientRect().width>0}", sel)
    check('telefon: sidebar lama tersembunyi', not vis('nav.rail.dsk'))
    check('telefon: bar atas ada Utama/Inbox/Menu', vis('.mnav') and pg.locator('.mnav button').count() == 3)
    check('tiada skrol ufuk halaman', pg.evaluate("()=>document.documentElement.scrollWidth<=window.innerWidth+1"))
    pg.screenshot(path=SH + 'm1.png')
    pg.click('.mmenu'); time.sleep(.2)
    check('laci terbuka', vis('.mdrawer'))
    heads = pg.locator('.mch span:first-child').all_inner_texts()
    check('6 kategori', heads == ['Pasukan', 'Perpindahan & scouting', 'Pertandingan', 'Kelab & kewangan', 'Pengurus', 'Bantuan & tetapan'], heads)
    check('item tidak ditunjuk terus (semua tertutup pada Utama)', pg.locator('.mitems').count() == 0)
    pg.click('.mch >> nth=0'); time.sleep(.2)
    items = pg.locator('.mitems button').all_inner_texts()
    check('Pasukan: 6 item', len(items) == 6 and any('Skuad' in x for x in items), items)
    check('hanya satu kategori terbuka', pg.locator('.mcat.open').count() == 1)
    pg.screenshot(path=SH + 'm2.png')
    pg.click('.mch >> nth=1'); time.sleep(.2)
    check('buka kategori lain tutup yang lama', pg.locator('.mcat.open').count() == 1 and 'Senarai pendek' in ' '.join(pg.locator('.mitems button').all_inner_texts()))
    pg.click('.mch >> nth=0'); pg.click('.mitems button >> text=Skuad'); time.sleep(.3)
    check('pilih item: pergi ke Skuad dan laci tutup', pg.evaluate("()=>UI.view")=='squad' and not vis('.mdrawer'))
    check('butang Menu tunjuk kategori semasa', 'Pasukan' in pg.locator('.mmenu').inner_text())
    pg.click('.mmenu'); time.sleep(.2)
    check('buka semula: kategori semasa terbuka', pg.locator('.mcat.open .mch span:first-child').inner_text()=='Pasukan')
    pg.screenshot(path=SH + 'm3.png')
    pg.click('.mback', position={'x':370,'y':400}); time.sleep(.2)
    check('klik latar tutup laci', not vis('.mdrawer'))
    pg.click('.mmenu'); pg.click('.mch >> nth=5'); pg.click('.mitems button >> text=Maklum balas'); time.sleep(.3)
    check('Maklum balas boleh dicapai', pg.evaluate("()=>UI.view")=='feedback')
    pg.evaluate("()=>{S.offers=[];ACT.nav('home')}"); pg.click('.mmenu'); pg.click('.mch >> nth=3'); pg.click('.mitems button >> text=Kad kelab'); time.sleep(1)
    check('Kad kelab buka modal dan tutup laci', pg.evaluate("()=>!!document.querySelector('#modal .cardwrap')") and not vis('.mdrawer'))
    check('tiada ralat halaman (telefon)', not errs, errs)
    d = b.new_context(viewport={'width': 1280, 'height': 800}); d.add_init_script(inv)
    pg2, errs2 = boot(d)
    vis2 = lambda sel: pg2.evaluate("(s)=>{const e=document.querySelector(s);return !!e&&getComputedStyle(e).display!=='none'&&e.getBoundingClientRect().width>0}", sel)
    check('desktop: sidebar kekal, tiada bar telefon', vis2('nav.rail.dsk') and not vis2('.mnav'))
    check('tiada ralat halaman (desktop)', not errs2, errs2)
    b.close()
srv.terminate(); print('SEMUA LULUS' if not fails else 'GAGAL', fails); sys.exit(1 if fails else 0)
