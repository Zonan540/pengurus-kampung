"""Fasa 8: penerangan pencapaian dirahsiakan sebelum dibuka; kad pengurus (PNG + QR)."""
import subprocess, sys, time, os, base64
from playwright.sync_api import sync_playwright
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'site')
srv = subprocess.Popen([sys.executable, '-m', 'http.server', '8819'], cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
fails = []
def check(n, ok, d=''):
    print(('PASS ' if ok else 'FAIL ') + n, d if not ok else ''); 
    if not ok: fails.append(n)
with sync_playwright() as p:
    b = p.chromium.launch(); ctx = b.new_context(viewport={'width': 1200, 'height': 900}); errs = []
    ctx.route('**/*', lambda r: r.abort() if (r.request.method == 'POST' or 'fonts.g' in r.request.url) else r.continue_())
    ctx.add_init_script("localStorage.setItem('pk3-invite', JSON.stringify({code:'AUTO',adm:0,at:'2026-10-28'}));localStorage.setItem('pk3-hidehelp','1')")
    pg = ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8819/index.html'); pg.wait_for_function("typeof newWorld==='function'", timeout=20000)
    pg.wait_for_function("!document.getElementById('splash')||getComputedStyle(document.getElementById('splash')).pointerEvents==='none'"); time.sleep(.5)
    pg.evaluate("()=>{UI.screen='game';newWorld();UI.selClub=S.lg[3][0];renderStart();document.getElementById('mgr').value='Zonan Uji';ACT.startgame()}")
    pg.evaluate("()=>{S.ach={};ACT.nav('ach')}")
    txt = pg.evaluate("()=>document.getElementById('app').innerText")
    d0 = pg.evaluate("()=>ACH.map(a=>a.d)")
    check('tiada penerangan terdedah bila belum dibuka', not any(d in txt for d in d0))
    pg.evaluate("()=>{achGive('hat','x');closeModal();ACT.nav('ach')}")
    txt = pg.evaluate("()=>document.getElementById('app').innerText")
    d = pg.evaluate("()=>ACH.find(a=>a.id==='hat').d")
    others = pg.evaluate("()=>ACH.filter(a=>a.id!=='hat').map(a=>a.d)")
    check('penerangan dibuka selepas dicapai', d in txt)
    check('yang lain kekal rahsia', not any(o in txt for o in others))
    pg.evaluate("()=>{closeModal();S.job.wdl=[12,5,7];S.job.rep=40;ACT.nav('profile')}")
    check('butang kad dikongsi ada', pg.evaluate("()=>!!document.querySelector('[data-act=mgrcard]')"))
    pg.evaluate("()=>mMgrCard()"); pg.wait_for_function("document.getElementById('cardimg')&&document.getElementById('cardimg').src.startsWith('data:image/png')", timeout=10000)
    dim = pg.evaluate("()=>[UI.cardCv.width,UI.cardCv.height,cardFile()]")
    check('kad 1080x1350 dan nama fail kad-pengurus', dim[0] == 1080 and dim[1] == 1350 and dim[2].startswith('kad-pengurus-'), dim)
    # QR region has dark pixels
    dark = pg.evaluate("()=>{const x=UI.cardCv.getContext('2d');const d=x.getImageData(914,1214,124,124).data;let n=0;for(let i=0;i<d.length;i+=4)if(d[i]<40)n++;return n}")
    check('QR dilukis', dark > 1500, dark)
    open('/tmp/claude-0/-home-claude/7fc64f2f-22b2-5147-8052-ef8c7da90f0a/scratchpad/mgrcard.png', 'wb').write(base64.b64decode(pg.evaluate("()=>UI.cardCv.toDataURL('image/png')").split(',')[1]))
    pg.evaluate("()=>{closeModal();mCard(S.user)}"); time.sleep(1.5)
    check('kad kelab masih guna nama fail kelab', pg.evaluate("()=>cardFile()").startswith('kad-kelab-'))
    # --- denda kad merah tamat tempoh
    pg.evaluate("()=>{closeModal();S.inbox=[];S.offers=[];S.dec=[];const pid=S.clubs[S.user].players[0];window.__pid=pid;inbox('inj','Uji digantung','x',{fine:{pid,amt:100,st:0}})}")
    check('denda baharu = perlu tindakan', pg.evaluate("()=>msgState(S.inbox[0])")=='act')
    pg.evaluate("()=>{S.inbox[0].d=addDays(curDate(),-20)}")
    check('denda lebih 14 hari = selesai', pg.evaluate("()=>msgState(S.inbox[0])")=='done')
    check('tab Perlu tindakan kosong', pg.evaluate("()=>S.inbox.filter(m=>{const x=msgState(m);return x==='act'||x==='dl'}).length")==0)
    pg.evaluate("()=>{S.inbox[0].d=curDate();S.players[window.__pid].club='x9'}")
    check('pemain sudah keluar = selesai', pg.evaluate("()=>msgState(S.inbox[0])")=='done')
    pg.evaluate("()=>{S.players[window.__pid].club=S.user;S.inbox[0].d=addDays(curDate(),-20);fineAct(S.inbox[0].id+'|1')}")
    check('denda tamat tempoh tak boleh dikenakan', pg.evaluate("()=>S.inbox[0].fine.st")==0)
    # --- lencana Pencapaian / Scouting hilang bila dibuka
    bdg=lambda k: pg.evaluate("(k)=>{const b=document.querySelector('nav.rail.dsk button[data-arg=\"'+k+'\"] .badge');return b?+b.textContent:0}",k)
    pg.evaluate("()=>{closeModal();S.ach={};S.achSeen={};S.celQ=[];ACT.nav('home');achGive('hat','x');closeModal();render()}")
    check('lencana Pencapaian ada bila ada yang baharu', bdg('ach')==1, bdg('ach'))
    pg.evaluate("()=>ACT.nav('ach')"); pg.evaluate("()=>ACT.nav('home')")
    check('lencana Pencapaian hilang selepas dibuka', bdg('ach')==0, bdg('ach'))
    pg.evaluate("()=>{achGive('gm','x');closeModal();render()}")
    check('pencapaian baharu muncul semula sebagai 1', bdg('ach')==1, bdg('ach'))
    pg.evaluate("()=>{ACT.nav('home');scEnsure();S.scT.push({id:'tz',st:'done',k:'f',rep:{list:[],d:curDate()}});render()}")
    check('lencana Scouting ada untuk laporan baharu', bdg('scouting')==1, bdg('scouting'))
    pg.evaluate("()=>ACT.nav('scouting')"); pg.evaluate("()=>ACT.nav('home')")
    check('lencana Scouting hilang selepas dibuka', bdg('scouting')==0, bdg('scouting'))
    # --- Beta 5: lencana Medical, Perpindahan (tawaran masuk) dan Lembaga hilang bila dibuka
    pg.evaluate("()=>{ACT.nav('home');const ps=S.clubs[S.user].players.map(id=>S.players[id]);window.__m1=ps[0].id;window.__m2=ps[1].id;ps.forEach(p=>{p.inj=0;delete p.injx});createInjury(ps[0],'match');render()}")
    check('lencana Medical ada untuk kecederaan baharu', bdg('medical')==1, bdg('medical'))
    pg.evaluate("()=>ACT.nav('medical')"); pg.evaluate("()=>ACT.nav('home')")
    check('lencana Medical hilang selepas dibuka', bdg('medical')==0, bdg('medical'))
    pg.evaluate("()=>{const p=S.players[window.__m2];createInjury(p,'match');render()}")
    check('kecederaan baharu muncul semula sebagai 1', bdg('medical')==1, bdg('medical'))
    pg.evaluate("()=>ACT.nav('medical')"); pg.evaluate("()=>ACT.nav('home')")
    check('lencana Medical hilang lagi', bdg('medical')==0, bdg('medical'))
    pg.evaluate("()=>{const f=Object.keys(S.clubs).find(id=>id!==S.user&&!S.clubs[id].foreign);S.offers=[];userOfferMsg({id:'oT1',kind:'buy',pid:window.__m1,from:f,fee:50000,exp:S.t+5});render()}")
    check('lencana Perpindahan ada untuk tawaran baharu', bdg('transfer')==1, bdg('transfer'))
    pg.evaluate("()=>{UI.tf.tab='cari';ACT.nav('transfer')}")
    check('lencana Perpindahan kekal bila bukan tab Tawaran', bdg('transfer')==1, bdg('transfer'))
    pg.evaluate("()=>ACT.tftab('tawaran')"); pg.evaluate("()=>ACT.nav('home')")
    check('lencana Perpindahan hilang selepas tab Tawaran dibuka', bdg('transfer')==0, bdg('transfer'))
    check('tawaran masih dalam senarai', pg.evaluate("()=>S.offers.length")==1)
    pg.evaluate("()=>{const f=Object.keys(S.clubs).find(id=>id!==S.user&&!S.clubs[id].foreign);S.job.offers.push({id:'jT1',cid:f,kind:'mid',exp:null});S.job.warn=1;render()}")
    check('lencana Lembaga ada (tawaran + amaran)', bdg('board')==2, bdg('board'))
    pg.evaluate("()=>ACT.nav('board')"); pg.evaluate("()=>ACT.nav('home')")
    check('lencana Lembaga hilang selepas dibuka', bdg('board')==0, bdg('board'))
    pg.evaluate("()=>{S.job.warn=0;render();S.job.warn=1;render()}")
    check('amaran lembaga baharu muncul semula', bdg('board')==1, bdg('board'))
    pg.evaluate("()=>{S.job.warn=0;S.job.offers=S.job.offers.filter(o=>o.id!=='jT1');render()}")
    check('tiada ralat halaman', not errs, errs)
    b.close()
srv.terminate(); print('SEMUA LULUS' if not fails else 'GAGAL', fails); sys.exit(1 if fails else 0)
